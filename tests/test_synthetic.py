"""Synthetic payroll regression tests. No OCR required for arithmetic tests."""
import json
from pathlib import Path
from dataclasses import replace
import pytest
from app.core import Sheet, ShiftDay, calculate_day, validate_sheet, summarize, save_session, load_session, normalize_time
from app.ocr import load_pages, _likely_blank, _cleanup_time
from app.report import export_excel

FIXTURES=Path(__file__).resolve().parents[1]/'test_samples'/'ground_truth.json'

@pytest.fixture(scope='module')
def sample_cases():
    return json.loads(FIXTURES.read_text(encoding='utf-8'))

def sheet_from_case(case):
    return Sheet('fictional-sheet.png','synthetic-hash',case['name'],'2026-10-24',days=[ShiftDay(**d) for d in case['punches']])

# Independent expected totals; these are not generated by the implementation.
EXPECTED={
 '01_Daytime.png':(40,40,80,0),
 '02_Overnight.png':(40,24,64,0),
 '03_SplitShifts.png':(40,24,64,0),
 '04_Overtime.png':(48,45,93,13),
 '05_MixedShifts.png':(20,16.75,36.75,0),
 '06_MultipleFonts.png':(23.5,17.5,41,0),
 '09_PhonePhoto.png':(24,16,40,0),
 '10_Blank.png':(0,0,0,0),
}

@pytest.mark.parametrize('filename', sorted(EXPECTED))
def test_real_schedule_patterns(sample_cases, filename):
    case=next(c for c in sample_cases if c['file']==filename)
    s=sheet_from_case(case)
    totals=summarize(s)
    assert (totals['week1'],totals['week2'],totals['total'],totals['overtime']) == EXPECTED[filename]
    assert validate_sheet(s) == []

@pytest.mark.parametrize('filename', ['07_MissingPunch.png','08_AmbiguousTime.png'])
def test_bad_punches_block_export(sample_cases, filename, tmp_path):
    case=next(c for c in sample_cases if c['file']==filename)
    s=sheet_from_case(case)
    assert validate_sheet(s)
    s.approved=True
    s.reviewed_days = [True] * 14
    with pytest.raises(ValueError, match='Errors for'):
        export_excel(str(tmp_path/'blocked.xlsx'),[s])
    assert not (tmp_path/'blocked.xlsx').exists()

def test_approved_valid_batch_export(sample_cases, tmp_path):
    sheets=[]
    for case in sample_cases:
        if case['file'] in EXPECTED:
            s=sheet_from_case(case)
            s.approved=True
            s.reviewed_days=[True]*14
            sheets.append(s)
    path=tmp_path/'approved_test_batch.xlsx'
    export_excel(str(path),sheets)
    assert path.exists()
    import zipfile
    import xml.etree.ElementTree as ET
    with zipfile.ZipFile(path) as z:
        names=z.namelist()
        assert 'xl/worksheets/sheet1.xml' in names
        assert 'xl/worksheets/sheet2.xml' in names
        summary=ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
        rows=summary.findall('.//{*}sheetData/{*}row')
        assert len(rows)>=len(sheets)+5
        assert b'formula' not in z.read('xl/worksheets/sheet1.xml') # native f tags not word formula
        assert b'<f>' in z.read('xl/worksheets/sheet1.xml')

def test_duplicate_person_period_is_blocked(tmp_path):
    a=Sheet('a','a','First Employee','2026-10-24',approved=True,reviewed_days=[True]*14)
    b=Sheet('b','b','FIRST EMPLOYEE','2026-10-24',approved=True,reviewed_days=[True]*14)
    with pytest.raises(ValueError,match='Duplicate employee'):
        export_excel(str(tmp_path/'duplicate.xlsx'),[a,b])

